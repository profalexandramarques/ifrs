#Calculadora versão 1
#Ler da tela 2 números reais
a = float(input("Digite um número: "))
b = float(input("Digite outro número: "))
#Soma
soma = a + b
print("A soma ",a,"+",b,"=",soma)
#Subtração
sub = a + b
print("A subtração ",a,"-",b,"=",sub)
#Multiplicação
mult = a * b
print("A multiplicação ",a,"*",b,"=",mult)
#Divisão
divisao = a / b
print("A divisão ",a,"/",b,"=",divisao)
